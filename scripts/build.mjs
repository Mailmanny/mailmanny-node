// ESM (dist/esm, also the CLI) + CommonJS (dist/cjs) builds with plain tsc, zero bundler.
import { execFileSync } from "node:child_process";
import { chmodSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const tsc = createRequire(import.meta.url).resolve("typescript/bin/tsc");
const run = (project) => execFileSync(process.execPath, [tsc, "-p", path.join(root, project)], { stdio: "inherit" });

// The version lives in package.json only; src/version.ts is generated from it, so a release is a one-line bump.
const { version } = JSON.parse(readFileSync(path.join(root, "package.json"), "utf8"));
writeFileSync(path.join(root, "src/version.ts"), `// Generated by scripts/build.mjs from package.json. Do not edit.\nexport const VERSION = "${version}";\n`);

rmSync(path.join(root, "dist"), { recursive: true, force: true });
run("tsconfig.json");
run("tsconfig.cjs.json");
writeFileSync(path.join(root, "dist/cjs/package.json"), JSON.stringify({ type: "commonjs" }, null, 2) + "\n");
chmodSync(path.join(root, "dist/esm/cli.js"), 0o755);
console.log("mailmanny: built dist/esm + dist/cjs");
